/**
 * Turning the parsed course and the audit findings into files a reviewer can
 * keep: a CSV inventory, a CSV of the findings, and a Markdown report.
 */
import type { Finding } from "./audit";
import { FINDING_CATEGORIES } from "./audit";
import type { ProcessedContent } from "@/lib/canvas/content";
import { describeQuestionCount, summariseQuestions } from "@/lib/canvas/quiz";
import { KIND_LABELS, type ContentType, type CourseExport, type CourseItem } from "@/lib/canvas/types";

/** Escape a value for a CSV cell. */
function csvCell(value: string | number | undefined): string {
  const text = value === undefined || value === null ? "" : String(value);
  if (/[",\n\r]/.test(text)) return `"${text.replace(/"/g, '""')}"`;
  return text;
}

/** Join values into a CSV row. */
function csvRow(values: (string | number | undefined)[]): string {
  return values.map(csvCell).join(",");
}

/**
 * A flat inventory of everything in the course.
 *
 * One row per item, in module order, with the details a reviewer would
 * otherwise have to open each item to find.
 */
export function toInventoryCsv(course: CourseExport, content: Map<string, ProcessedContent>): string {
  const rows = [
    csvRow([
      "Module",
      "Module state",
      "Item",
      "Type",
      "State",
      "Points",
      "Due",
      "Group",
      "Body characters",
      "Links",
      "Notes",
    ]),
  ];

  for (const item of course.items) {
    const processed = content.get(item.id);
    const bodyLength = processed?.text.length ?? 0;
    const linkCount = processed?.links.length ?? 0;

    rows.push(
      csvRow([
        item.moduleTitle,
        item.moduleState,
        item.title,
        KIND_LABELS[item.kind],
        item.state,
        item.assignment?.pointsPossible ?? item.quiz?.pointsPossible,
        item.assignment?.dueAt ?? item.quiz?.dueAt,
        item.assignment?.groupTitle,
        bodyLength,
        linkCount,
        itemNotes(item),
      ]),
    );
  }

  for (const item of course.orphans) {
    const processed = content.get(item.id);

    rows.push(
      csvRow([
        "(not in a module)",
        "",
        item.title,
        KIND_LABELS[item.kind],
        item.state,
        "",
        "",
        "",
        processed?.text.length ?? 0,
        processed?.links.length ?? 0,
        "Not in any module",
      ]),
    );
  }

  return rows.join("\r\n");
}

/** A short note about an item, for the inventory. */
function itemNotes(item: CourseItem): string {
  const notes: string[] = [];

  if (item.unresolved) notes.push(item.unresolvedReason ?? "Not resolved");
  if (item.url) notes.push(item.url);
  if (item.quiz) {
    const summary = summariseQuestions(item.quiz);
    if (summary.hasQuestions) notes.push(describeQuestionCount(summary));
    if (item.quiz.accessCode) notes.push("Has an access code");
  }
  if (item.kind === "page" && item.page?.frontPage) notes.push("Course front page");

  return notes.join("; ");
}

/** The findings as a CSV, one row per finding. */
export function toFindingsCsv(findings: Finding[]): string {
  const rows = [csvRow(["Severity", "Category", "Finding", "Detail", "Items", "Notes"])];

  for (const finding of findings) {
    rows.push(
      csvRow([
        finding.severity,
        FINDING_CATEGORIES.find((category) => category.id === finding.category)?.label ?? finding.category,
        finding.title,
        finding.detail,
        finding.itemIds.length,
        finding.notes.join("; "),
      ]),
    );
  }

  return rows.join("\r\n");
}

/** A Markdown report of the course and its findings. */
export function toMarkdownReport(
  course: CourseExport,
  findings: Finding[],
  content: Map<string, ProcessedContent>,
): string {
  const lines: string[] = [];

  lines.push(`# ${course.meta.title}`);
  lines.push("");
  lines.push(`_Generated by Drawbridge from ${course.meta.sourceName}. Nothing left the browser._`);
  lines.push("");

  const meta: string[] = [];
  if (course.meta.code) meta.push(`- **Course code:** ${course.meta.code}`);
  if (course.meta.accountName) meta.push(`- **Account:** ${course.meta.accountName}`);
  if (course.meta.domain) meta.push(`- **Exported from:** ${course.meta.domain}`);
  if (course.meta.exportedAt) meta.push(`- **Exported:** ${course.meta.exportedAt}`);
  lines.push(...meta, "");

  lines.push("## At a glance");
  lines.push("");
  lines.push("| Measure | Count |");
  lines.push("| --- | ---: |");
  lines.push(`| Modules | ${course.modules.length} |`);
  lines.push(`| Module items | ${course.items.length} |`);
  lines.push(`| Assignments | ${countBy(course.items, "assignment")} |`);
  lines.push(`| Quizzes | ${countBy(course.items, "quiz")} |`);
  lines.push(`| Pages | ${countBy(course.items, "page")} |`);
  lines.push(`| Discussions | ${countBy(course.items, "discussion")} |`);
  lines.push(`| External links | ${countBy(course.items, "external-url")} |`);
  lines.push(`| Files | ${course.files.length} |`);
  lines.push(`| Content outside any module | ${course.orphans.length} |`);
  lines.push("");

  lines.push("## Findings");
  lines.push("");

  if (findings.length === 0) {
    lines.push("Nothing to report.");
    lines.push("");
  } else {
    for (const category of FINDING_CATEGORIES) {
      const inCategory = findings.filter((finding) => finding.category === category.id);
      if (inCategory.length === 0) continue;

      lines.push(`### ${category.label}`);
      lines.push("");

      for (const finding of inCategory) {
        lines.push(`- **${finding.title}** _(${finding.severity})_`);
        lines.push(`  ${finding.detail}`);
        for (const note of finding.notes) lines.push(`  - ${note}`);
      }

      lines.push("");
    }
  }

  lines.push("## Modules");
  lines.push("");

  for (const module of course.modules) {
    lines.push(`### ${module.title}`);
    lines.push("");
    lines.push(`_${module.state}${module.items.length === 0 ? " — no items" : ` — ${module.items.length} items`}_`);
    lines.push("");

    for (const moduleItem of module.items) {
      const item = course.items.find((candidate) => candidate.itemId === moduleItem.id);
      if (!item) continue;

      const processed = content.get(item.id);
      const details: string[] = [KIND_LABELS[item.kind]];

      if (item.assignment?.pointsPossible !== undefined) details.push(`${item.assignment.pointsPossible} points`);
      if (item.quiz?.questionCount) details.push(`${item.quiz.questionCount} questions`);
      if (item.url) details.push(item.url);
      if (item.unresolved) details.push("not in the manifest");

      lines.push(`- ${moduleItem.title} — ${details.join(" · ")}`);
      if (processed?.text) {
        lines.push(`  > ${firstSentence(processed.text)}`);
      }
    }

    lines.push("");
  }

  return lines.join("\n");
}

/** How many items of a kind the course has. */
function countBy(items: CourseItem[], kind: ContentType): number {
  return items.filter((item) => item.kind === kind).length;
}

/** The first sentence of a piece of text, for a one-line summary. */
function firstSentence(text: string): string {
  const trimmed = text.trim();
  const stop = trimmed.search(/[.!?](\s|$)/);
  const sentence = stop === -1 ? trimmed : trimmed.slice(0, stop + 1);
  return sentence.length > 220 ? `${sentence.slice(0, 217)}…` : sentence;
}
